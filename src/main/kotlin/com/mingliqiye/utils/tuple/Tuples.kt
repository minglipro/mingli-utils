package com.mingliqiye.utils.tuple


import java.io.Serializable

/**
 * 元组抽象基类。
 *
 * 提供按索引访问元素以及转换为列表、集合的能力，子类通过 componentN 函数暴露各元素。
 *
 * @param size 元组包含的元素个数
 */
abstract class Tuple(val size: Int = 1) : Serializable, Iterable<Any>, Comparable<Tuple> {

	/**
	 * 按字典序比较当前元组与另一个元组。
	 *
	 * 从第 1 个元素开始逐位比较：两个元素类型相同且都实现 [Comparable] 时按自然顺序比较，
	 * 否则按元素的字符串形式（[toString]）比较。
	 * 公共位置元素全部相等时，元素个数较少的元组视为较小。
	 *
	 * @param other 要比较的目标元组
	 * @return 负数、零或正数，分别表示当前元组小于、等于或大于 [other]
	 */
	override fun compareTo(other: Tuple): Int {
		val minSize = minOf(size, other.size)
		for (i in 0..<minSize) {
			val a = get(i)
			val b = other.get(i)
			val result = if (a is Comparable<*> && b is Comparable<*> && a.javaClass == b.javaClass) {
				@Suppress("UNCHECKED_CAST")
				(a as Comparable<Any>).compareTo(b)
			} else {
				a.toString().compareTo(b.toString())
			}
			if (result != 0) return result
		}
		return size.compareTo(other.size)
	}

	override fun iterator(): Iterator<Any> {
		return toMutableList().iterator()
	}

	/**
	 * 将元组的所有元素转换为列表。
	 *
	 * @return 包含全部元素的列表
	 */
	open fun toList(): List<Any> {
		return (0..<size).map { get(it) }
	}

	/**
	 * 将元组的所有元素转换为可变列表。
	 *
	 * @return 包含全部元素的可变列表
	 */
	open fun toMutableList(): MutableList<Any> {
		return toList().toMutableList()
	}

	/**
	 * 将元组的所有元素转换为集合（去重）。
	 *
	 * @return 包含全部元素的集合
	 */
	open fun toSet(): Set<Any> {
		return toList().toSet()
	}

	/**
	 * 将元组的所有元素转换为可变集合（去重）。
	 *
	 * @return 包含全部元素的可变集合
	 */
	open fun toMutableSet(): MutableSet<Any> {
		return toList().toMutableSet()
	}

	/**
	 * 按索引获取元组中的元素。
	 *
	 * @param index 元素索引（从 0 开始）
	 * @return 对应位置的元素
	 * @throws IndexOutOfBoundsException 如果索引超出元素个数
	 */
	operator fun get(index: Int): Any {
		if (index >= size) {
			throw IndexOutOfBoundsException("index $index is out size $size")
		}
		return this.javaClass.getDeclaredMethod("component${index + 1}").invoke(this)
	}

